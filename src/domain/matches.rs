//! A match of a series, as stored in `matches`: two teams of a pool, its round of the round
//! robin, and its state, with the score of a result.
//!
//! Its public key is its pool and its number within the pool, from 1, in the order of the
//! rounds. Phase, state and side are TEXT columns without `CHECK`: these enums parse them, so
//! that the final phase (#10) is a code change, not a table rebuild. Its slot (date, time,
//! court) comes with the calendar (#9).

use core::str::FromStr;

use super::pool::PoolName;

/// `matches.phase`: the part of the tournament a match belongs to, as Frontis's `phase` names it.
/// The final phase comes with #10.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Phase {
    /// The round robin of a pool.
    Pool,
}

impl Phase {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::Pool => "pool",
        }
    }
}

impl FromStr for Phase {
    type Err = ();

    fn from_str(s: &str) -> Result<Self, ()> {
        match s {
            "pool" => Ok(Self::Pool),
            _ => Err(()),
        }
    }
}

/// One of the two teams of a match, in the order of [`Match::teams`]: `matches.forfeit`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Side {
    A,
    B,
}

impl Side {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::A => "a",
            Self::B => "b",
        }
    }

    /// Its index in [`Match::teams`] and in a score.
    pub(crate) fn index(self) -> usize {
        match self {
            Self::A => 0,
            Self::B => 1,
        }
    }
}

impl FromStr for Side {
    type Err = ();

    fn from_str(s: &str) -> Result<Self, ()> {
        match s {
            "a" => Ok(Self::A),
            "b" => Ok(Self::B),
            _ => Err(()),
        }
    }
}

/// `matches.state`, with the score of a result in the order of [`Match::teams`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum MatchState {
    /// Generated by the draw, not played yet.
    Scheduled,
    /// Put off to another slot. The calendar (#9) sets it: no route of the pools does.
    Postponed,
    /// Played: one team reached the target score of the series, the other stayed below it.
    Played { score: [i64; 2] },
    /// The team `by` forfeited: the other team gets the target score, and it gets 0.
    Forfeit { by: Side, score: [i64; 2] },
}

impl MatchState {
    /// The states of a result, `played` and `forfeit`: a series with one of them is no longer
    /// drawn again, and its teams no longer move.
    pub(crate) const RESULTS: [&'static str; 2] = ["played", "forfeit"];

    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::Scheduled => "scheduled",
            Self::Postponed => "postponed",
            Self::Played { .. } => "played",
            Self::Forfeit { .. } => "forfeit",
        }
    }

    /// The score of a result.
    pub(crate) fn score(self) -> Option<[i64; 2]> {
        match self {
            Self::Played { score } | Self::Forfeit { score, .. } => Some(score),
            Self::Scheduled | Self::Postponed => None,
        }
    }

    /// The team that forfeited.
    pub(crate) fn forfeit(self) -> Option<Side> {
        match self {
            Self::Forfeit { by, .. } => Some(by),
            Self::Scheduled | Self::Postponed | Self::Played { .. } => None,
        }
    }

    /// Whether the match has a result, played or forfeit.
    pub(crate) fn is_result(self) -> bool {
        self.score().is_some()
    }

    /// The state of a stored row: `None` when its columns do not fit together, such as a played
    /// match without a score or a scheduled one with a forfeit.
    pub(crate) fn from_columns(
        state: &str,
        score: Option<[i64; 2]>,
        forfeit: Option<Side>,
    ) -> Option<Self> {
        match (state, score, forfeit) {
            ("scheduled", None, None) => Some(Self::Scheduled),
            ("postponed", None, None) => Some(Self::Postponed),
            ("played", Some(score), None) => Some(Self::Played { score }),
            ("forfeit", Some(score), Some(by)) => Some(Self::Forfeit { by, score }),
            _ => None,
        }
    }
}

/// A match of a pool.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct Match {
    pub(crate) phase: Phase,
    pub(crate) pool: PoolName,
    /// The public key within the pool, from 1, in the order of the rounds.
    pub(crate) number: i64,
    /// The round of the circle method, from 1.
    pub(crate) round: i64,
    /// The numbers of its two teams: the better seed first.
    pub(crate) teams: [i64; 2],
    pub(crate) state: MatchState,
}

#[cfg(test)]
mod tests {
    use super::{MatchState, Phase, Side};

    #[test]
    fn enums_round_trip_through_their_text_form() {
        assert_eq!("pool".parse::<Phase>(), Ok(Phase::Pool), "the pool phase");
        assert_eq!(Phase::Pool.as_str(), "pool", "Frontis's phase name");
        assert_eq!(
            "final".parse::<Phase>(),
            Err(()),
            "the final phase comes with #10"
        );
        for side in [Side::A, Side::B] {
            assert_eq!(side.as_str().parse::<Side>(), Ok(side), "{side:?}");
        }
        assert_eq!("c".parse::<Side>(), Err(()), "two sides only");
    }

    #[test]
    fn a_state_reads_back_from_its_columns() {
        let states = [
            MatchState::Scheduled,
            MatchState::Postponed,
            MatchState::Played { score: [40, 31] },
            MatchState::Forfeit {
                by: Side::B,
                score: [40, 0],
            },
        ];
        for state in states {
            assert_eq!(
                MatchState::from_columns(state.as_str(), state.score(), state.forfeit()),
                Some(state),
                "{state:?}"
            );
        }
        for (state, score, forfeit) in [
            ("played", None, None),
            ("scheduled", Some([40, 31]), None),
            ("forfeit", Some([40, 0]), None),
            ("played", Some([40, 31]), Some(Side::A)),
            ("cancelled", None, None),
        ] {
            assert_eq!(
                MatchState::from_columns(state, score, forfeit),
                None,
                "{state} with {score:?} and {forfeit:?} does not fit"
            );
        }
    }

    #[test]
    fn only_played_and_forfeit_are_results() {
        assert!(!MatchState::Scheduled.is_result(), "scheduled");
        assert!(!MatchState::Postponed.is_result(), "postponed");
        assert!(MatchState::Played { score: [30, 12] }.is_result(), "played");
        assert!(
            MatchState::Forfeit {
                by: Side::A,
                score: [0, 30]
            }
            .is_result(),
            "forfeit"
        );
        assert_eq!(
            MatchState::RESULTS,
            [
                MatchState::Played { score: [0, 0] }.as_str(),
                MatchState::Forfeit {
                    by: Side::A,
                    score: [0, 0]
                }
                .as_str()
            ],
            "the stored names of the results"
        );
    }
}
